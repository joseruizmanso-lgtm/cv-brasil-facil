// Función para cambiar el idioma
function cambiarIdioma(idioma) {
  // Cambiar el atributo lang del HTML
  document.documentElement.lang = idioma === 'es' ? 'es' : 'pt-BR';

  // Recorrer todos los elementos que tienen data-i18n
  document.querySelectorAll('[data-i18n]').forEach(elemento => {
    const clave = elemento.getAttribute('data-i18n');
    if (traducciones[idioma][clave]) {
      elemento.innerText = traducciones[idioma][clave];
    }
  });

  // Actualizar el estado de los botones
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === idioma) {
      btn.classList.add('active');
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.classList.remove('active');
      btn.setAttribute('aria-pressed', 'false');
    }
  });

  // Guardar la preferencia en el navegador
  localStorage.setItem('idiomaPreferido', idioma);
}

// Detectar clics en los botones de idioma
document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', (e) => {
    const idiomaSeleccionado = e.target.getAttribute('data-lang');
    cambiarIdioma(idiomaSeleccionado);
  });
});

// Al cargar la página, verificar si hay un idioma guardado
document.addEventListener('DOMContentLoaded', () => {
  const idiomaGuardado = localStorage.getItem('idiomaPreferido');
  if (idiomaGuardado) {
    cambiarIdioma(idiomaGuardado);
  }
});